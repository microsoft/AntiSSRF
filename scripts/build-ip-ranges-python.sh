# Script to build ipaddress_ranges.py from IPAddressRanges.json
# Generates a Python class with static IP address range tuples

set -e

# Get the directory where this script is located
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
JSON_FILE="$SCRIPT_DIR/../config/IPAddressRanges.json"
PY_FILE="$SCRIPT_DIR/../python/src/AntiSSRF/ipaddress_ranges.py"

# Check if jq is available
if ! command -v jq &> /dev/null; then
  echo "Error: jq is required but not installed."
  echo "Install on WSL/Ubuntu: sudo apt-get update && sudo apt-get install -y jq"
  echo "Install on macOS: brew install jq"
    exit 1
fi

# Check if JSON file exists
if [[ ! -f "$JSON_FILE" ]]; then
    echo "Error: IPAddressRanges.json not found in $SCRIPT_DIR"
    exit 1
fi

# Generate Python file
echo "# Copyright (c) Microsoft Corporation." > "$PY_FILE"
echo "# Licensed under the MIT License." >> "$PY_FILE"
echo "" >> "$PY_FILE"
echo "# Auto-generated from IPAddressRanges.json" >> "$PY_FILE"
echo "# Do not edit this file manually" >> "$PY_FILE"
echo "" >> "$PY_FILE"
echo "from typing import Final" >> "$PY_FILE"
echo "" >> "$PY_FILE"
echo "" >> "$PY_FILE"
echo "# Static IP address ranges for AntiSSRF protection" >> "$PY_FILE"
echo "class IPAddressRanges:" >> "$PY_FILE"
echo '    """Static IP address ranges for AntiSSRF protection."""' >> "$PY_FILE"

# Generate individual property declarations (JSON camelCase keys -> snake_case)
jq -r '
  to_entries
  | map(select(.key != "_sources" and .value.standaloneVariable == true))
  | .[]
  | (.key | gsub("(?<a>[a-z0-9])(?<b>[A-Z])"; "\(.a)_\(.b)") | ascii_downcase) as $name
  | "    " + $name + ": Final[tuple[str, ...]] = (" + (.value.cidr | map("\"" + . + "\"") | join(", ")) + ",)"
' "$JSON_FILE" >> "$PY_FILE"

# Add recommended_latest alias that matches recommended_v1
echo "" >> "$PY_FILE"
echo "    # recommended_latest always points to the latest version" >> "$PY_FILE"
echo "    recommended_latest: Final[tuple[str, ...]] = recommended_v1" >> "$PY_FILE"

echo "Successfully generated $PY_FILE"
